"""Generate/check the fixed three-shape Unreal pilot table; never import arbitrary content."""
import argparse
import hashlib
import json
from pathlib import Path

from construction_geometry import Q, ROTATIONS, SUPPORTED, canonical_payload, validate_payload

TARGET = Path(__file__).resolve().parents[1] / 'GameClient/Source/ShatteredFrontier/Private/Construction/SFConstructionGeometryData.h'


def generated():
    out = ['// Generated by tools/Generate-ConstructionGeometryHeader.py; do not edit.',
           '#pragma once', 'namespace SFConstructionData {',
           'struct FShape { const TCHAR* Key; const ANSICHAR* Payload; const TCHAR* Hash; TArray<FIntVector> Vertices; TArray<TArray<int32>> Faces; };',
           'inline const TArray<FShape>& Shapes() { static const TArray<FShape> Data = {']
    for key in SUPPORTED:
        payload = canonical_payload(key)
        validate_payload(payload)
        obj = json.loads(payload)
        vertices = ','.join('FIntVector(%d,%d,%d)' % tuple(p) for p in obj['vertices'])
        faces = ','.join('{' + ','.join(map(str, face)) + '}' for face in obj['parts'][0])
        out.append('{TEXT("%s"),R"SF(%s)SF",TEXT("%s"),{%s},{%s}},' %
                   (key, payload.decode(), hashlib.sha256(payload).hexdigest(), vertices, faces))
    out += ['}; return Data; }', 'inline const TArray<TArray<FIntVector>>& Rotations() { static const TArray<TArray<FIntVector>> Data = {']
    for rotation in ROTATIONS:
        out.append('{' + ','.join('FIntVector(%d,%d,%d)' % axis for axis in rotation) + '},')
    out += ['}; return Data; }', '} // namespace SFConstructionData', '']
    return '\n'.join(out)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generated()
    if args.check:
        if not TARGET.exists() or TARGET.read_text(encoding='utf-8') != text:
            raise SystemExit('Unreal pilot table differs from canonical source; regenerate and review.')
        print('Unreal pilot table matches all three canonical payloads, faces and 24 rotations.')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(text, encoding='utf-8', newline='\n')
