"""Import the pilot item icons and reference them from the item definitions.

Run in the open editor: python tools/Run-InEditor.py tools/Import-PilotItemIcons.py
Sources live in GameClient/ArtSource/UI/Icons-v1 (generated by generate.sh there). Textures land in
/Game/Frontier/UI/Icons and are re-imported on each run; a definition's Description is only filled when empty.
"""
import os

import unreal


SOURCE_DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'GameClient', 'ArtSource', 'UI', 'Icons-v1')
ICON_PATH = '/Game/Frontier/UI/Icons'
ITEM_PATH = '/Game/Frontier/Gameplay/Pilot'
# (png stem, item asset, description to use when the definition has none)
ICONS = (
    ('oak_log', 'DA_OakLog', 'Heavy felled oak, ready for the sawmill.'),
    ('iron_ore', 'DA_IronOre', 'Raw iron-bearing rock. Smelt it into ingots.'),
    ('rough_timber', 'DA_RoughTimber', 'Rough-sawn oak boards for building and crafting.'),
    ('iron_ingot', 'DA_IronIngot', 'Smelted iron bar for tools and fittings.'),
    ('boar_hide', 'DA_BoarHide', 'Coarse hide taken from a wild boar.'),
    ('iron_axe', 'DA_IronAxe', None),
    ('iron_pickaxe', 'DA_IronPickaxe', None),
)

BUILD_ICONS = ('build_foundation', 'build_wall', 'build_door', 'build_roof')  # construction catalogue tiles; no item definition
tasks = []
for stem in [icon[0] for icon in ICONS] + list(BUILD_ICONS):
    source = os.path.normpath(os.path.join(SOURCE_DIR, stem + '.png'))
    if not os.path.isfile(source):
        raise RuntimeError('Missing icon source ' + source)
    task = unreal.AssetImportTask()
    task.set_editor_property('filename', source)
    task.set_editor_property('destination_path', ICON_PATH)
    task.set_editor_property('destination_name', 'T_Icon_' + stem)
    task.set_editor_property('replace_existing', True)
    task.set_editor_property('automated', True)
    task.set_editor_property('save', False)
    tasks.append(task)
unreal.AssetToolsHelpers.get_asset_tools().import_asset_tasks(tasks)

library = unreal.EditorAssetLibrary
done = []
for stem, item_name, description in ICONS:
    texture = library.load_asset(ICON_PATH + '/T_Icon_' + stem)
    if texture is None:
        raise RuntimeError('Import failed for ' + stem)
    texture.set_editor_property('lod_group', unreal.TextureGroup.TEXTUREGROUP_UI)
    texture.set_editor_property('mip_gen_settings', unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS)
    texture.set_editor_property('compression_settings', unreal.TextureCompressionSettings.TC_EDITOR_ICON)
    texture.set_editor_property('never_stream', True)
    item = library.load_asset(ITEM_PATH + '/' + item_name)
    if item is None:
        raise RuntimeError('Missing item definition ' + item_name)
    item.set_editor_property('icon', texture)
    if description and not str(item.get_editor_property('description')):
        item.set_editor_property('description', unreal.Text(description))
    if not library.save_loaded_asset(texture) or not library.save_loaded_asset(item):
        raise RuntimeError('Could not save ' + stem)
    done.append(item_name)

for stem in BUILD_ICONS:
    texture = library.load_asset(ICON_PATH + '/T_Icon_' + stem)
    if texture is None:
        raise RuntimeError('Import failed for ' + stem)
    texture.set_editor_property('lod_group', unreal.TextureGroup.TEXTUREGROUP_UI)
    texture.set_editor_property('mip_gen_settings', unreal.TextureMipGenSettings.TMGS_NO_MIPMAPS)
    texture.set_editor_property('compression_settings', unreal.TextureCompressionSettings.TC_EDITOR_ICON)
    texture.set_editor_property('never_stream', True)
    if not library.save_loaded_asset(texture):
        raise RuntimeError('Could not save ' + stem)
    done.append('T_Icon_' + stem)

unreal.log('PILOT_ITEM_ICONS_IMPORTED ' + ', '.join(done))
