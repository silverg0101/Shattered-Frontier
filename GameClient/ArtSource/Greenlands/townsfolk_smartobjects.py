"""Smart Object placements for the townsfolk prototype (AI Townsfolk doc, section 9 step 2): a door per building, a stall
spot per market stall and vendor, and the benches the prop pass placed. Residents claim their slots at home, work and
errand stops (SFTownsfolk.cpp builds the USmartObjectDefinitions and creates the objects at world start).

    python townsfolk_smartobjects.py                  # any Python 3: writes silverbrook-smartobjects.json from the building roster
    python tools/Run-InEditor.py GameClient/ArtSource/Greenlands/townsfolk_smartobjects.py   # in the open editor: adds the benches

Reads silverbrook-buildings.json (written by build_silverbrook.py), the layout's building sizes and, in the editor, the
benches place_props.py put in the level (tag SilverbrookProp, label ending _Bench). A building's front is its actor's local +Y,
so the door sits d/2 along (-sin yaw, cos yaw) from its centre. `facing` is the world direction the object faces (degrees).
"""
import json, math, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
OUT = ROOT / 'silverbrook-smartobjects.json'
STALLS = {'market_stall', 'armor_vendor', 'weapons_vendor'}
NO_DOOR = {'docks', 'wharf'} | STALLS


def front(yaw):
    r = math.radians(yaw)
    return -math.sin(r), math.cos(r)


def plan(L, buildings, benches=()):
    """Objects in a stable order: doors and stalls from the roster, then benches (x, y metres, facing degrees)."""
    T = L['building_types']
    objs = []
    for b in buildings:
        if b['kind'] in NO_DOOR - STALLS:
            continue
        fx, fy = front(b['yaw'])
        off = T[b['kind']][1] / 2
        objs.append(dict(kind='stall' if b['kind'] in STALLS else 'door', owner=b['label'],
                         at=[round(b['at'][0] + fx * off, 2), round(b['at'][1] + fy * off, 2)],
                         facing=round(math.degrees(math.atan2(fy, fx)) % 360, 1)))
    for i, (x, y, facing) in enumerate(benches):
        objs.append(dict(kind='bench', owner=f'Bench_{i:02d}', at=[round(x, 2), round(y, 2)], facing=round(facing % 360, 1)))
    return objs


def check(objs, census, buildings):
    out = []
    owners = {(o['kind'], o['owner']) for o in objs}
    roster = {b["label"] for b in buildings}  # gates and patrols are workplaces without a building
    if len(owners) != len(objs):
        out.append('duplicate smart object owners')
    for h in census['households']:
        if ('door', h['home']) not in owners:
            out.append(f"home {h['home']} has no door")
    for w in census['workplaces']:
        if w["label"] in roster and w["kind"] not in NO_DOOR and ("door", w["label"]) not in owners:
            out.append(f"workplace {w['label']} has no door")
    for m in census['markets']:
        if ('stall', m['label']) not in owners:
            out.append(f"market {m['label']} has no stall")
    return out


def write(objs):
    OUT.write_text(json.dumps(dict(
        _about='Generated by townsfolk_smartobjects.py from silverbrook-buildings.json and the placed benches; do not hand-edit.',
        objects=objs), indent=1) + '\n', encoding='utf-8', newline='\n')


def build_in_editor(L=None):
    """Writes the file with the benches found in the open level; returns a summary."""
    import unreal as u
    L = L or json.loads((ROOT / 'silverbrook-town-layout.json').read_text(encoding='utf-8'))
    buildings = json.loads((ROOT / 'silverbrook-buildings.json').read_text(encoding='utf-8'))['buildings']
    benches = []
    for a in u.get_editor_subsystem(u.EditorActorSubsystem).get_all_level_actors():
        if 'SilverbrookProp' in [str(t) for t in a.tags] and a.get_actor_label().endswith('_Bench'):
            p = a.get_actor_location()
            fx, fy = front(a.get_actor_rotation().yaw)
            benches.append((p.x / 100, p.y / 100, math.degrees(math.atan2(fy, fx))))
    benches.sort()
    objs = plan(L, buildings, benches)
    problems = check(objs, json.loads((ROOT / "silverbrook-census.json").read_text(encoding="utf-8")), buildings)
    write(objs)  # a stale census (rerun townsfolk_census.py) is reported, not fatal to a map rebuild
    return f'problems={problems} doors={sum(o["kind"] == "door" for o in objs)} stalls={sum(o["kind"] == "stall" for o in objs)} benches={len(benches)}'


